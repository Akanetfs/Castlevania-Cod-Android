std::string Utf8(const wchar_t* w) {
    std::string s;
    for (; w && *w; w++) s += *w < 0x80 ? char(*w) : '?';
    return s;
}

// the log's lines to logcat as well: stderr is read on a thread of its own
void LogToLogcat() {
    int fds[2];
    if (pipe(fds)) return;
    dup2(fds[1], STDERR_FILENO);
    close(fds[1]);
    std::thread([fd = fds[0]] {
        char buf[1024];
        std::string line;
        for (ssize_t n; (n = read(fd, buf, sizeof(buf))) > 0;) {
            line.append(buf, size_t(n));
            for (size_t nl; (nl = line.find('\n')) != std::string::npos; line.erase(0, nl + 1))
                __android_log_write(ANDROID_LOG_INFO, "BLACK", line.substr(0, nl).c_str());
        }
    }).detach();
}

// A crash in the native code leaves no trace in the log: it is written in memory and the process dies first. This
// writes where it happened (the signal, the registers, the code's address inside its library and a walk up the host
// stack) and flushes, then hands the signal back to Android. Resolve an address with
//   llvm-symbolizer -e <unstripped libmain.so> 0x<offset>
// The recompiled functions are named sub_<guest address>, so the name alone says where in the game it was.
struct sigaction g_old_action[NSIG];

void LogAddress(const char* what, uintptr_t address) {
    Dl_info info{};
    if (address && dladdr(reinterpret_cast<void*>(address), &info) && info.dli_fname) {
        const char* base = std::strrchr(info.dli_fname, '/');
        LOGE("  %s %p  %s+0x%zx", what, reinterpret_cast<void*>(address), base ? base + 1 : info.dli_fname,
             size_t(address - reinterpret_cast<uintptr_t>(info.dli_fbase)));
    } else {
        LOGE("  %s %p", what, reinterpret_cast<void*>(address));
    }
}

void CrashHandler(int sig, siginfo_t* info, void* context) {
    static std::atomic<bool> reported{false};
    if (!reported.exchange(true)) {
        auto* uc = static_cast<ucontext_t*>(context);
        const auto& m = uc->uc_mcontext;
        LOGE("CRASH: signal %d (%s), code %d, fault address %p, thread %d", sig, strsignal(sig), info->si_code,
             info->si_addr, int(gettid()));
        LogAddress("pc", uintptr_t(m.pc));
        LogAddress("lr", uintptr_t(m.regs[30]));
        LOGE("  sp %p fp %p", reinterpret_cast<void*>(uintptr_t(m.sp)), reinterpret_cast<void*>(uintptr_t(m.regs[29])));
        for (int i = 0; i < 29; i += 4)
            LOGE("  x%-2d %016llx x%-2d %016llx x%-2d %016llx x%-2d %016llx", i, (unsigned long long)m.regs[i], i + 1,
                 (unsigned long long)m.regs[i + 1], i + 2, (unsigned long long)m.regs[i + 2], i + 3,
                 (unsigned long long)m.regs[i + 3]);
        logx::Flush();
        // a walk up the frame pointers: stops at the first thing that does not look like a frame
        uintptr_t sp = uintptr_t(m.sp), fp = uintptr_t(m.regs[29]);
        for (int i = 0; i < 24 && fp && !(fp & 7) && fp > sp && fp - sp < (64u << 20); i++) {
            auto* frame = reinterpret_cast<uintptr_t*>(fp);
            LogAddress("frame", frame[1]);
            if (frame[0] <= fp) break;
            fp = frame[0];
        }
        logx::Flush();
    }
    // back to what Android had (its own crash report), and the fault happens again there
    if (sig >= 0 && sig < NSIG) sigaction(sig, &g_old_action[sig], nullptr);
}

void InstallCrashHandler() {
    static uint8_t stack[64 * 1024];
    stack_t ss{};
    ss.ss_sp = stack;
    ss.ss_size = sizeof(stack);
    sigaltstack(&ss, nullptr);
    struct sigaction sa{};
    sa.sa_sigaction = CrashHandler;
    sa.sa_flags = SA_SIGINFO | SA_ONSTACK;
    sigemptyset(&sa.sa_mask);
    for (int sig : {SIGSEGV, SIGBUS, SIGILL, SIGFPE, SIGABRT, SIGTRAP}) sigaction(sig, &sa, &g_old_action[sig]);
    std::set_terminate([] {
        if (auto e = std::current_exception()) {
            try {
                std::rethrow_exception(e);
            } catch (const std::exception& ex) {
                LOGE("CRASH: uncaught C++ exception: %s", ex.what());
            } catch (...) {
                LOGE("CRASH: uncaught C++ exception of an unknown type");
            }
        } else {
            LOGE("CRASH: std::terminate without an exception");
        }
        logx::Flush();
        std::abort();
    });
}

